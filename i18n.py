# Hláška ve frontě je text z jazyka, ve kterém chyba vznikla.
# Při zobrazení se pozná ve všech katalozích a vrátí se v aktuálním jazyce.
_PLACEHOLDER = re.compile(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}")
_ERROR_EXACT: dict[str, str] = {}
_ERROR_TEMPLATES: list[tuple[re.Pattern[str], str]] = []


def _template_pattern(template: str) -> re.Pattern[str]:
    parts: list[str] = []
    last = 0
    for match in _PLACEHOLDER.finditer(template):
        parts.append(re.escape(template[last : match.start()]))
        parts.append(f"(?P<{match.group(1)}>.+?)")
        last = match.end()
    parts.append(re.escape(template[last:]))
    return re.compile("^" + "".join(parts) + "$", re.DOTALL)


def _index_errors() -> None:
    seen: set[tuple[str, str]] = set()
    for catalog in _STRINGS.values():
        for key, template in catalog.items():
            if not key.startswith("err."):
                continue
            sig = (key, template)
            if sig in seen:
                continue
            seen.add(sig)
            if "{" in template:
                _ERROR_TEMPLATES.append((_template_pattern(template), key))
            else:
                _ERROR_EXACT.setdefault(template, key)
    _ERROR_TEMPLATES.sort(key=lambda item: len(item[0].pattern), reverse=True)


_index_errors()


def translate_known_error(text: str) -> Optional[str]:
    """Vrátí hlášku v aktuálním jazyce, pokud text patří do katalogu err.*."""
    if not text:
        return None
    key = _ERROR_EXACT.get(text)
    if key:
        return t(key)
    for pattern, key in _ERROR_TEMPLATES:
        match = pattern.fullmatch(text)
        if match:
            return t(key, **match.groupdict())
    return None
