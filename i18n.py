def option_label(options: list[tuple[str, str]], value: str, fallback: str) -> str:
    for label, item in options:
        if item == value:
            return label
    return fallback


def option_value(options: list[tuple[str, str]], label: str, fallback: str) -> str:
    for text, item in options:
        if text == label:
            return item
    return fallback


